-- The shop's tables. `npm run db:setup` runs this file and then seed.sql; both can run again on a set-up database.

CREATE TABLE IF NOT EXISTS products (
  sku text PRIMARY KEY,
  name text NOT NULL,
  description text NOT NULL,
  price_cents integer NOT NULL CHECK (price_cents > 0),
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

CREATE TABLE IF NOT EXISTS customers (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  first_name text NOT NULL,
  last_name text NOT NULL,
  email text NOT NULL UNIQUE,
  phone text,
  country text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- A database set up before first and last name were kept apart has a single `name` column: split it once.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'customers' AND column_name = 'name') THEN
    ALTER TABLE customers ADD COLUMN IF NOT EXISTS first_name text;
    ALTER TABLE customers ADD COLUMN IF NOT EXISTS last_name text;
    UPDATE customers SET first_name = split_part(name, ' ', 1),
      last_name = COALESCE(NULLIF(trim(substr(name, length(split_part(name, ' ', 1)) + 1)), ''), '')
      WHERE first_name IS NULL;
    ALTER TABLE customers ALTER COLUMN first_name SET NOT NULL;
    ALTER TABLE customers ALTER COLUMN last_name SET NOT NULL;
    ALTER TABLE customers DROP COLUMN name;
  END IF;
END $$;

-- One row per checkout that got as far as pricing. `status` is 'pending' while the invoice is issued, then 'placed',
-- or 'rejected' with the reason in `failure` when the invoice could not be issued.
CREATE TABLE IF NOT EXISTS orders (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
  customer_id integer NOT NULL REFERENCES customers (id),
  product_sku text NOT NULL REFERENCES products (sku),
  quantity integer NOT NULL CHECK (quantity > 0),
  sample_bag boolean NOT NULL DEFAULT false,
  coupon_code text,
  address text NOT NULL,
  country text NOT NULL,
  delivery_date date NOT NULL,
  subtotal_cents integer NOT NULL,
  discount_cents integer NOT NULL DEFAULT 0,
  shipping_cents integer NOT NULL DEFAULT 0,
  total_cents integer NOT NULL,
  status text NOT NULL CHECK (status IN ('pending', 'placed', 'rejected')),
  failure text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status, created_at DESC);

-- Issued for placed orders only; an invoice never has a negative total.
CREATE TABLE IF NOT EXISTS invoices (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  order_id integer NOT NULL UNIQUE REFERENCES orders (id),
  number text NOT NULL UNIQUE,
  total_cents integer NOT NULL CHECK (total_cents >= 0),
  issued_at timestamptz NOT NULL DEFAULT now()
);
